// Pure managed: linked into Reactor.Tests, so nothing here may touch WinUI.
namespace Microsoft.UI.Reactor.AppTests.Host.SelfTest.TransformsMatrix;

/// <summary>One observed field that differs between two ledgers. A null side means absent.</summary>
internal sealed record LedgerDifference(string Case, string Step, string Field, string? Before, string? After)
{
    public override string ToString() => $"{Case} / {Step} / {Field}: {Show(Before)} -> {Show(After)}";

    private static string Show(string? v) => v is null ? "(absent)" : Quote(v);
}

/// <summary>
/// The spec 066 behaviour ledger (§12.1 C): one record per matrix case, one line per lifecycle step,
/// every observed value a string. The file is written in a fixed order with one step per line, so a
/// PR's diff of it shows reviewers exactly which behaviours changed.
/// </summary>
internal sealed class TransformsLedger
{
    public const int Schema = 1;
    public const string BaselineDirectory = "tests/Reactor.AppTests.Host/SelfTest/Baselines";
    public const string LedgerFile = "transforms-ledger.json";
    public const string ExpectedFile = "transforms-ledger.expected.json";
    public const string KnownFile = "transforms-ledger.known.json";

    /// <summary>Fields holding DIP coordinates, compared within ±<see cref="Tolerance"/> (§12.1 C.5).</summary>
    public static readonly string[] GeometricFields = ["pose", "active", "uia", "ttv"];

    public const double Tolerance = 2;

    public int Seed { get; set; } = MatrixGenerator.DefaultSeed;

    public OrderedDictionary<string, LedgerCase> Cases { get; } = new(StringComparer.Ordinal);

    public LedgerCase Case(string id)
    {
        if (!Cases.TryGetValue(id, out var c)) Cases[id] = c = new LedgerCase();
        return c;
    }

    public static TransformsLedger Parse(string json)
    {
        using var doc = JsonDocument.Parse(json);
        var root = doc.RootElement;
        int schema = root.GetProperty("schema").GetInt32();
        if (schema != Schema) throw new FormatException($"Transforms ledger schema {schema} is not {Schema}.");
        var ledger = new TransformsLedger { Seed = root.GetProperty("seed").GetInt32() };
        foreach (var c in root.GetProperty("cases").EnumerateObject())
        {
            var lc = ledger.Case(c.Name);
            foreach (var s in c.Value.EnumerateObject())
            {
                if (s.Name == "dims") { lc.Dims = s.Value.GetString(); continue; }
                var fields = lc.Step(s.Name);
                foreach (var f in s.Value.EnumerateObject()) fields[f.Name] = f.Value.GetString() ?? "";
            }
        }

        return ledger;
    }

    public string Write()
    {
        var sb = new StringBuilder();
        sb.Append("{\n  \"schema\": ").Append(Schema).Append(",\n  \"seed\": ").Append(Seed).Append(",\n");
        sb.Append("  \"note\": \"Generated by the TransformsMatrix selftest (spec 066 §12.1). Don't edit by hand; see TESTING.md.\",\n");
        sb.Append("  \"cases\": {");
        bool firstCase = true;
        foreach (var (id, c) in Cases)
        {
            sb.Append(firstCase ? "\n" : ",\n").Append("    ").Append(Json(id)).Append(": {");
            firstCase = false;
            var lines = new List<string>();
            if (c.Dims is not null) lines.Add($"\"dims\": {Json(c.Dims)}");
            foreach (var (step, fields) in c.Steps)
                lines.Add($"{Json(step)}: {{ {string.Join(", ", fields.Select(f => $"{Json(f.Key)}: {Json(f.Value)}"))} }}");
            sb.Append('\n').Append(string.Join(",\n", lines.Select(l => "      " + l))).Append("\n    }");
        }

        sb.Append("\n  }\n}\n");
        return sb.ToString();
    }

    /// <summary>Equality for one field: exact, except geometric fields, which allow ±2 DIP per number.</summary>
    public static bool FieldEquals(string field, string? a, string? b)
    {
        if (a == b) return true;
        if (a is null || b is null || Array.IndexOf(GeometricFields, field) < 0) return false;
        var ta = Tokens(a);
        var tb = Tokens(b);
        if (ta.Length != tb.Length) return false;
        for (int i = 0; i < ta.Length; i++)
        {
            bool na = double.TryParse(ta[i], NumberStyles.Float, CultureInfo.InvariantCulture, out var da);
            bool nb = double.TryParse(tb[i], NumberStyles.Float, CultureInfo.InvariantCulture, out var db);
            if (na != nb) return false;
            if (na ? Math.Abs(da - db) > Tolerance : ta[i] != tb[i]) return false;
        }

        return true;
    }

    /// <summary>Every field that differs between two records of the same case.</summary>
    public static IEnumerable<LedgerDifference> CompareCase(string id, LedgerCase? before, LedgerCase? after)
    {
        if (before?.Dims != after?.Dims) yield return new LedgerDifference(id, "dims", "dims", before?.Dims, after?.Dims);
        var steps = (before?.Steps.Keys ?? Enumerable.Empty<string>()).Concat(after?.Steps.Keys ?? Enumerable.Empty<string>()).Distinct(StringComparer.Ordinal);
        foreach (var step in steps)
        {
            OrderedDictionary<string, string>? b = null, a = null;
            before?.Steps.TryGetValue(step, out b);
            after?.Steps.TryGetValue(step, out a);
            var fields = (b?.Keys ?? Enumerable.Empty<string>()).Concat(a?.Keys ?? Enumerable.Empty<string>()).Distinct(StringComparer.Ordinal);
            foreach (var field in fields)
            {
                string? bv = null, av = null;
                b?.TryGetValue(field, out bv);
                a?.TryGetValue(field, out av);
                if (!FieldEquals(field, bv, av)) yield return new LedgerDifference(id, step, field, bv, av);
            }
        }
    }

    public static List<LedgerDifference> Diff(TransformsLedger before, TransformsLedger after)
    {
        var diffs = new List<LedgerDifference>();
        foreach (var id in before.Cases.Keys.Concat(after.Cases.Keys).Distinct(StringComparer.Ordinal))
        {
            before.Cases.TryGetValue(id, out var b);
            after.Cases.TryGetValue(id, out var a);
            diffs.AddRange(CompareCase(id, b, a));
        }

        return diffs;
    }

    /// <summary>
    /// Copies each committed value that the observation matches within tolerance, so regenerating
    /// the ledger only rewrites the lines whose behaviour actually changed.
    /// </summary>
    public static void KeepUnchanged(LedgerCase committed, LedgerCase observed)
    {
        foreach (var (step, fields) in observed.Steps)
        {
            if (!committed.Steps.TryGetValue(step, out var old)) continue;
            foreach (var key in fields.Keys.ToArray())
                if (old.TryGetValue(key, out var v) && FieldEquals(key, v, fields[key])) fields[key] = v;
        }
    }

    internal static string[] Tokens(string s) => Regex.Split(s, @"[,;= ]+").Where(t => t.Length > 0).ToArray();

    internal static string Json(string s) => Quote(s);
}

internal sealed class LedgerCase
{
    public string? Dims { get; set; }

    public OrderedDictionary<string, OrderedDictionary<string, string>> Steps { get; } = new(StringComparer.Ordinal);

    public OrderedDictionary<string, string> Step(string name)
    {
        if (!Steps.TryGetValue(name, out var s)) Steps[name] = s = new OrderedDictionary<string, string>(StringComparer.Ordinal);
        return s;
    }
}

/// <summary>
/// One declared behaviour change (<c>transforms-ledger.expected.json</c>). Selectors accept <c>*</c>
/// wildcards; <c>before</c>/<c>after</c> are exact values or <c>*</c>.
/// </summary>
internal sealed record LedgerExpectation(string Case, string Step, string Field, string Before, string After, string Reason)
{
    /// <summary>A §9 row of spec 066 or the issue the change fixes (§12.1 C.2).</summary>
    public static readonly Regex ReasonPattern = new(@"^(§9 row \d+|fixes #\d+)\b", RegexOptions.CultureInvariant);

    public bool Matches(LedgerDifference d) =>
        Glob.IsMatch(Case, d.Case) && Glob.IsMatch(Step, d.Step) && Glob.IsMatch(Field, d.Field)
        && (Before == "*" || Before == (d.Before ?? "(absent)")) && (After == "*" || After == (d.After ?? "(absent)"));

    public static List<LedgerExpectation> ParseFile(string json)
    {
        using var doc = JsonDocument.Parse(json);
        return doc.RootElement.GetProperty("expectations").EnumerateArray().Select(e => new LedgerExpectation(
            e.GetProperty("case").GetString()!,
            e.TryGetProperty("step", out var s) ? s.GetString()! : "*",
            e.GetProperty("field").GetString()!,
            e.TryGetProperty("before", out var b) ? b.GetString()! : "*",
            e.TryGetProperty("after", out var a) ? a.GetString()! : "*",
            e.GetProperty("reason").GetString()!)).ToList();
    }

    public override string ToString() =>
        $"{{ \"case\": {J(Case)}, \"step\": {J(Step)}, \"field\": {J(Field)}, \"before\": {J(Before)}, \"after\": {J(After)}, \"reason\": {J(Reason)} }}";

    public static LedgerExpectation Suggest(LedgerDifference d) =>
        new(d.Case, d.Step, d.Field, d.Before ?? "(absent)", d.After ?? "(absent)", "§9 row N | fixes #NNNN");

    private static string J(string s) => Quote(s);
}

/// <summary>The outcome of checking a PR's ledger against its base (§12.1 C.2 and C.3).</summary>
internal sealed record LedgerCheck(
    IReadOnlyList<LedgerDifference> Undeclared,
    IReadOnlyList<LedgerExpectation> Stale,
    IReadOnlyList<LedgerDifference> ControlGroup,
    IReadOnlyList<LedgerExpectation> BadReason)
{
    public bool Passed => Undeclared.Count == 0 && Stale.Count == 0 && ControlGroup.Count == 0 && BadReason.Count == 0;

    public static LedgerCheck Run(TransformsLedger baseLedger, TransformsLedger head, IReadOnlyList<LedgerExpectation> expectations)
    {
        var diffs = TransformsLedger.Diff(baseLedger, head);
        // The control group can't be excused: only its rent-as-transformed step may change (layer 4).
        var control = diffs.Where(d => d.Case == ControlGroupId && d.Step != MatrixCase.StepName(MatrixStep.RentTransformed)).ToList();
        var undeclared = diffs.Except(control).Where(d => !expectations.Any(e => e.Matches(d))).ToList();
        var stale = expectations.Where(e => !diffs.Except(control).Any(e.Matches)).ToList();
        var bad = expectations.Where(e => !LedgerExpectation.ReasonPattern.IsMatch(e.Reason)).ToList();
        return new LedgerCheck(undeclared, stale, control, bad);
    }

    public static readonly string ControlGroupId = new MatrixCase(TransformAxis.None, TransitionAxis.None, FeatureAxis.None,
        WrapperAxis.Direct, FlowAxis.Ltr, MotionAxis.Enabled, UserCodeAxis.None, VariantAxis.A).Id;

    public string Describe(int max = 40)
    {
        var sb = new StringBuilder();
        string path = $"{TransformsLedger.BaselineDirectory}/{TransformsLedger.ExpectedFile}";
        if (Undeclared.Count > 0)
        {
            sb.AppendLine($"{Undeclared.Count} behaviour change(s) between the base ledger and this PR's ledger are not declared:");
            foreach (var d in Undeclared.Take(max)) sb.AppendLine("  " + d);
            if (Undeclared.Count > max) sb.AppendLine($"  ...and {Undeclared.Count - max} more");
            sb.AppendLine($"If a change is intended, declare it in {path}, citing the spec 066 §9 row it introduces or the");
            sb.AppendLine("issue it fixes. Selectors take * wildcards, so one entry can cover a family of cases. For example:");
            foreach (var d in Undeclared.Take(3)) sb.AppendLine("  " + LedgerExpectation.Suggest(d));
            sb.AppendLine("If a change is not intended, it's a regression: fix the product code, not the ledger.");
        }

        if (ControlGroup.Count > 0)
        {
            sb.AppendLine($"The control group ({ControlGroupId}) changed. No layer may change it, and an expectation can't excuse it:");
            foreach (var d in ControlGroup.Take(max)) sb.AppendLine("  " + d);
        }

        if (Stale.Count > 0)
        {
            sb.AppendLine($"{Stale.Count} expectation(s) in {path} match no change between the base ledger and this PR's ledger.");
            sb.AppendLine("Expectations are per PR: remove the ones a merged PR already landed, or fix the selector.");
            foreach (var e in Stale.Take(max)) sb.AppendLine("  " + e);
        }

        if (BadReason.Count > 0)
        {
            sb.AppendLine("Each expectation's reason must start with \"§9 row N\" or \"fixes #NNNN\":");
            foreach (var e in BadReason.Take(max)) sb.AppendLine("  " + e);
        }

        sb.Append("See TESTING.md, \"Transforms matrix and behaviour ledger\".");
        return sb.ToString();
    }
}

/// <summary>
/// A known disagreement between <c>main</c> and the composition model (<c>transforms-ledger.known.json</c>).
/// §12.1 B: when <c>main</c> disagrees with the model, the case is recorded with an issue link instead
/// of bending the model. <see cref="Part"/> is <c>pose</c>, <c>active</c> or <c>motion:&lt;channel&gt;</c>;
/// <see cref="Dims"/> matches the case's pairwise dimensions, for example <c>*user=SetFacade*</c>.
/// </summary>
internal sealed record KnownDifference(string Case, string Dims, string Step, string Part, string Issue, string Note)
{
    public static readonly Regex IssuePattern = new(@"^(#\d+|§9 row \d+)$", RegexOptions.CultureInvariant);

    public bool Matches(string caseId, string dims, string step, string part) =>
        Glob.IsMatch(Case, caseId) && Glob.IsMatch(Dims, dims) && Glob.IsMatch(Step, step) && Glob.IsMatch(Part, part);

    public static List<KnownDifference> ParseFile(string json)
    {
        using var doc = JsonDocument.Parse(json);
        return doc.RootElement.GetProperty("known").EnumerateArray().Select(e => new KnownDifference(
            e.GetProperty("case").GetString()!,
            e.TryGetProperty("dims", out var d) ? d.GetString()! : "*",
            e.TryGetProperty("step", out var s) ? s.GetString()! : "*",
            e.GetProperty("part").GetString()!,
            e.GetProperty("issue").GetString()!,
            e.TryGetProperty("note", out var n) ? n.GetString()! : "")).ToList();
    }

    public override string ToString() => $"{Case} [{Dims}] / {Step} / {Part} ({Issue})";
}

internal static class JsonQuoting
{
    /// <summary>A JSON string literal, keeping §, + and quotes-free text readable for diffs.</summary>
    public static string Quote(string s) => "\"" + JsonEncodedText.Encode(s, JavaScriptEncoder.UnsafeRelaxedJsonEscaping) + "\"";
}

internal static class Glob
{
    public static bool IsMatch(string pattern, string value) =>
        pattern == "*" || pattern == value
        || (pattern.Contains('*') && Regex.IsMatch(value, "^" + Regex.Escape(pattern).Replace(@"\*", ".*") + "$", RegexOptions.CultureInvariant));
}
